# PROGRAMACIÓN ORIENTADA A OBJETOS (POO) — CLASES

# Definición de una clase básica
class Pajaro:
    pass  # la clase no tiene atributos ni métodos aún

# Crear objetos (instancias) de la clase
mi_Pajaro = Pajaro()       # objeto 1
otro_Pajaro = Pajaro()     # objeto 2

# Mostrar los objetos creados
print(mi_Pajaro, otro_Pajaro)
